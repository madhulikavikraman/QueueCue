import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:queuecue_server/ai/lint.dart';
import 'package:queuecue_server/ai/schemas.dart';
import 'package:queuecue_server/config.dart';

/// Writes PROMPTS.md (every AI prompt + its JSON schema) from the source of
/// truth: lib/ai/prompts/*.md and lib/ai/schemas.dart.
void main() {
  final cfg = Config.load();
  final b = StringBuffer();
  final grounding = File(p.join(cfg.promptsDir, '_grounding.md')).readAsStringSync().trim();
  b.writeln('# QueueCue AI prompts\n');
  b.writeln('Generated by `dart run bin/dump_prompts.dart` from `server/lib/ai/prompts/` and `server/lib/ai/schemas.dart`. Do not edit by hand.\n');
  b.writeln('Every call goes to the local Ollama model (`${cfg.model}`, set in `server/config.json`) with the JSON schema in the `format` field (structured output). '
      'The server validates the response against the schema, retries once with the validation errors, then falls back to the cached or offline result with a visible notice.\n');
  b.writeln('## How the pitch is made\n');
  b.writeln('1. **Voice Profile** (`voice_profile`, once at onboarding) from the 60-second recording (whisper.cpp, on the laptop) and 2 typed answers.');
  b.writeln('2. **Pitch Facts** (`pitch_facts`): 1-2 relevant projects with the detail that makes them real, one connection to a listed role, one booth-specific question.');
  b.writeln('3. **Draft** (`pitch_draft`): 55-80 words in the student\'s voice + question + 2 talking points + a sentence-by-sentence source trace.');
  b.writeln('4. **Critic** (`pitch_critic`, separate prompt) plus a deterministic lint that cannot be skipped. Rewrite (`pitch_rewrite`) if anything fails or any score is below 4. Max 2 rewrites.');
  b.writeln('5. Student controls: More like me / Shorter / Different project / Edit. Edits are stored on the Voice Profile and fed into future drafts.\n');
  b.writeln('Fit scoring (`booth_fit`) runs **twice** with the role list in two different orders and averages the result. Resumes are blinded first (name, email, phone, links, pronouns, years/dates, addresses removed).\n');
  b.writeln('## Shared grounding rules (inserted into every prompt)\n');
  b.writeln('```text\n$grounding\n```\n');
  b.writeln('## Banned words and phrases (critic + deterministic lint)\n');
  b.writeln(bannedPhrases.map((w) => '`$w`').join(', ') + ', and any "As a ___ student" opener.\n');
  final order = ['resume_parse', 'voice_profile', 'booth_fit', 'pitch_facts', 'pitch_draft', 'pitch_critic', 'pitch_rewrite', 'drop_note', 'recruiter_summary', 'followup_email'];
  for (final name in order) {
    final txt = File(p.join(cfg.promptsDir, '$name.md')).readAsStringSync().replaceAll('{{GROUNDING}}', '{{GROUNDING}}  (see above)').trim();
    b.writeln('## `$name`\n');
    b.writeln('Prompt file: `server/lib/ai/prompts/$name.md`\n');
    b.writeln('```text\n$txt\n```\n');
    b.writeln('JSON schema:\n');
    b.writeln('```json\n${const JsonEncoder.withIndent('  ').convert(Schemas.all[name])}\n```\n');
  }
  File(p.join(cfg.serverDir, '..', 'PROMPTS.md')).writeAsStringSync(b.toString());
  stdout.writeln('Wrote PROMPTS.md');
}
